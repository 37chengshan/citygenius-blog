export function getLang() {
  try { return localStorage.getItem('cg-lang') || 'en'; } catch (e) { return 'en'; }
}

export function applyI18n(lang) {
  if (lang !== 'en' && lang !== 'zh') lang = 'en';
  const dict = STR[lang] || {};
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const v = dict[el.dataset.i18n];
    if (v != null) el.innerHTML = v;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    const v = dict[el.dataset.i18nPh];
    if (v != null) el.setAttribute('placeholder', v);
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    const v = dict[el.dataset.i18nAriaLabel];
    if (v != null) el.setAttribute('aria-label', v);
  });
  syncLangToggle(lang);
}

export function setLang(lang) {
  if (lang !== 'en' && lang !== 'zh') lang = 'en';
  document.documentElement.dataset.lang = lang;
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  try { localStorage.setItem('cg-lang', lang); } catch (e) {}
  applyI18n(lang);
}

function syncLangToggle(lang) {
  document.querySelectorAll('.lang-toggle .lang-opt').forEach((o) => {
    o.classList.toggle('active', o.dataset.setlang === lang);
  });
}
